export function getTekrarDizaynReport(unitId?: string, bookNumber?: number, grade?: number): TekrarDizaynReport {
  if (grade === 6 || (unitId && (unitId.startsWith('g6-') || unitId.includes('g6')))) {
    if (bookNumber === 2 || (unitId && (unitId.includes('unit-5') || unitId.includes('unit-6') || unitId.includes('unit-7') || unitId.includes('u5') || unitId.includes('u6') || unitId.includes('u7')))) {
      return tekrarDizaynReportDataGrade6Book2;
    }
    return tekrarDizaynReportDataGrade6Book1;
  }
  if (grade === 7 || (unitId && (unitId.startsWith('g7-') || unitId.includes('g7')))) {
    if (bookNumber === 2 || (unitId && (unitId.includes('unit-4') || unitId.includes('unit-5') || unitId.includes('unit-6') || unitId.includes('unit-7') || unitId.includes('u4') || unitId.includes('u5') || unitId.includes('u6') || unitId.includes('u7')))) {
      return tekrarDizaynReportDataGrade7Book2;
    }
    return tekrarDizaynReportDataGrade7Book1;
  }
  if (bookNumber === 2) return tekrarDizaynReportDataBook2;
  if (bookNumber === 1) return tekrarDizaynReportDataBook1;
  if (unitId && (unitId.includes('unit-4') || unitId.includes('unit-5') || unitId.includes('unit-6') || unitId.includes('unit-7') || unitId.startsWith('unit4') || unitId.startsWith('unit5') || unitId.startsWith('unit6') || unitId.startsWith('unit7'))) {
    return tekrarDizaynReportDataBook2;
  }
  return tekrarDizaynReportDataBook1;
}
